create table management_record_aud (
  id                   uuid not null,
  rev                  bigint not null references audit_revision(id),
  revtype              smallint,
  record_type          text not null,
  association_id       uuid,
  farmer_id            uuid,
  property_id          uuid,
  plot_id              uuid,
  performed_on         date,
