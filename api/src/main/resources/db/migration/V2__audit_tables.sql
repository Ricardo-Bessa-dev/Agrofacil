-- V2__audit_tables.sql: tabelas do Hibernate Envers (histórico de alterações, ADR-10).
-- Geradas a partir das entidades (doc 2 §1.5) e ajustadas aos tipos da V1. A coluna version não é
-- auditada (padrão do Envers). Mudou uma entidade @Audited? Crie uma migração nova para o _aud dela.

-- Revisão: quem fez, de qual aparelho e por onde (MOBILE, WEB ou SYSTEM).
create table audit_revision (
  id          bigint generated by default as identity primary key,
  revision_at bigint not null,          -- milissegundos desde 1970 (UTC)
  user_id     uuid,
  device_id   uuid,
  source      text
);

create table app_user_aud (
  id                uuid not null,
  rev               bigint not null references audit_revision(id),
  revtype           smallint,
  association_id    uuid,
  role              text,
  name              text,
  cpf               char(11),
  email             text,
  phone             text,
  status            text,
  terms_accepted_at timestamptz,
  terms_version     text,
  created_at        timestamptz,
  updated_at        timestamptz,
  deleted_at        timestamptz,
  primary key (rev, id)
);

create table farmer_aud (
  user_id           uuid not null,
  rev               bigint not null references audit_revision(id),
  revtype           smallint,
  group_id          uuid,
  caf_number        text,
  group_joined_year integer,
  postal_code       char(8),
  uf                char(2),
  municipality_id   integer,
  locality          text,
  street            text,
  number            text,
  complement        text,
  notes             text,
  primary key (rev, user_id)
);

create table spg_group_aud (
  id              uuid not null,
