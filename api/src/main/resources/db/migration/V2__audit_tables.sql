);

create table input_purchase_aud (
  record_id        uuid not null,
  rev              bigint not null,
  input_id         uuid,
  input_other_name text,
  quantity         numeric(12,3),
  quantity_unit    text,
  supplier         text,
  primary key (rev, record_id),
  foreign key (rev, record_id) references management_record_aud (rev, id)
);

create table outflow_aud (
  record_id          uuid not null,
  rev                bigint not null,
  crop_id            uuid,
