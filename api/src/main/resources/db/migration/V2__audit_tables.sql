-- Subtipos: mesma chave (rev, record_id) da linha-mãe auditada.
create table planting_aud (
  record_id            uuid not null,
  rev                  bigint not null,
  crop_id              uuid,
  crop_other_name      text,
  variety              text,
  planted_area         numeric(12,3),
  planted_area_unit    text,
  planted_area_m2      numeric(14,2),
  propagation_type     text,
  propagation_quantity numeric(12,3),
  propagation_unit     text,
  seed_origin          text,
  seed_supplier        text,
  expected_harvest_on  date,
  cycle_status         text,
  finished_on          date,
  primary key (rev, record_id),
  foreign key (rev, record_id) references management_record_aud (rev, id)
);

create table input_application_aud (
  record_id         uuid not null,
