  planting_id       uuid,
  input_id          uuid,
  input_other_name  text,
  purpose           text,
  quantity          numeric(12,3),
  quantity_unit     text,
  applied_area      numeric(12,3),
  applied_area_unit text,
  applied_area_m2   numeric(14,2),
  primary key (rev, record_id),
  foreign key (rev, record_id) references management_record_aud (rev, id)
);

create table harvest_aud (
